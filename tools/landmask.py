"""Rasterise Natural Earth land polygons (public domain) into a 1-degree bitmask for the pixel globe.

Usage: python tools/landmask.py ne_110m_land.geojson
Source: https://github.com/nvkelso/natural-earth-vector/blob/master/geojson/ne_110m_land.geojson
"""
import base64
import json
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
W, H = 360, 180


def rings(geojson: dict) -> list[np.ndarray]:
    out = []
    for feature in geojson["features"]:
        geom = feature["geometry"]
        polys = [geom["coordinates"]] if geom["type"] == "Polygon" else geom["coordinates"]
        for poly in polys:
            out += [np.asarray(ring, dtype=float) for ring in poly]
    return out


def rasterise(ring_list: list[np.ndarray], w: int = W, h: int = H) -> np.ndarray:
    # Even-odd scanline fill at cell centres; row 0 is 90N, column 0 is 180W.
    mask = np.zeros((h, w), dtype=bool)
    lons = -180 + (np.arange(w) + 0.5) * 360 / w
    for j in range(h):
        lat = 90 - (j + 0.5) * 180 / h
        xs = []
        for ring in ring_list:
            a, b = ring[:-1], ring[1:]
            crosses = (a[:, 1] > lat) != (b[:, 1] > lat)
            if not crosses.any():
                continue
            a, b = a[crosses], b[crosses]
            t = (lat - a[:, 1]) / (b[:, 1] - a[:, 1])
            xs += list(a[:, 0] + t * (b[:, 0] - a[:, 0]))
        xs.sort()
        for x0, x1 in zip(xs[0::2], xs[1::2]):
            mask[j] |= (lons >= x0) & (lons < x1)
    return mask


def to_ts(mask: np.ndarray) -> str:
    b64 = base64.b64encode(np.packbits(mask.ravel()).tobytes()).decode()
    return (
        "// Generated by tools/landmask.py from Natural Earth 1:110m land (public domain,\n"
        "// naturalearthdata.com). 1-degree cells, row 0 = 90N, column 0 = 180W.\n"
        f"export const LAND_W = {mask.shape[1]};\n"
        f"export const LAND_H = {mask.shape[0]};\n"
        f'export const LAND_B64 = "{b64}";\n'
    )


def main(geojson_path: str) -> None:
    mask = rasterise(rings(json.loads(Path(geojson_path).read_text())))
    out = ROOT / "remotion" / "src" / "engine" / "landmask.ts"
    out.write_text(to_ts(mask))
    print(f"land {mask.mean() * 100:.1f}% of cells -> {out}")


if __name__ == "__main__":
    main(sys.argv[1])
